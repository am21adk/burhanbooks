// Writes supabase/04_seed.sql from src/data/books.seed.json, so the book
// the database starts with is exactly the one local builds show.
//
//   node scripts/make-seed-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const books = JSON.parse(fs.readFileSync(path.join(ROOT, 'src', 'data', 'books.seed.json'), 'utf8'));
const columns = ['slug', 'title', 'author', 'contributors', 'description', 'price_pence',
  'cover_url', 'cover_small_url', 'cover_width', 'cover_height', 'is_published', 'sort_order', 'updated_at'];

/** Dollar-quoted, so apostrophes and quote marks in the copy need no escaping. */
const literal = (/** @type {unknown} */ value) => {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  const text = String(value);
  if (text.includes('$seed$')) throw new Error('Seed text contains $seed$');
  return `$seed$${text}$seed$`;
};

const rows = books.map((/** @type {Record<string, unknown>} */ book) => `  (${columns.map((c) => literal(book[c])).join(',\n   ')})`);
const sql = `-- Burhan Books, 4 of 4: the book the shop starts with.
-- Generated by scripts/make-seed-sql.mjs from src/data/books.seed.json.
-- Taken word for word from the old site. Price and payment link are left
-- empty for the owner to add in the admin. Running this again never
-- overwrites a book that's already there.

insert into public.books (${columns.join(', ')})
values
${rows.join(',\n')}
on conflict (slug) do nothing;
`;
fs.writeFileSync(path.join(ROOT, 'supabase', '04_seed.sql'), sql);
console.log(`Wrote supabase/04_seed.sql (${books.length} book${books.length === 1 ? '' : 's'})`);
